package main

import (
	"embed"
	"fmt"

	"github.com/wailsapp/wails/v2"
	"github.com/wailsapp/wails/v2/pkg/options"
	"github.com/wailsapp/wails/v2/pkg/options/assetserver"
)

//go:embed all:frontend/dist
var assets embed.FS

func main() {
	// Create an instance of the app structure
	app := NewApp()

	// Create application with options
	err := wails.Run(&options.App{
		// Version comes from the embedded wails.json, so the title bar always
		// agrees with the build (see version.go).
		Title:  fmt.Sprintf("%s v%s", appInfo.ProductName, appInfo.Version),
		Width:  1024,
		Height: 768,
		AssetServer: &assetserver.Options{
			Assets: assets,
		},
		BackgroundColour: &options.RGBA{R: 27, G: 38, B: 54, A: 1},
		// Without this, a file dragged in from Explorer arrives as an empty
		// text/plain payload - the DOM never sees where it came from. Wails'
		// own handler resolves the real absolute paths instead. Elements opt in
		// by setting --wails-drop-target: drop in CSS.
		DragAndDrop: &options.DragAndDrop{
			EnableFileDrop: true,
		},
		OnStartup: app.startup,
		Bind: []interface{}{
			app,
		},
	})

	if err != nil {
		println("Error:", err.Error())
	}
}
